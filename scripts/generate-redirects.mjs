/**
 * Builds public/_redirects (Cloudflare static assets format).
 *
 * Why it exists: Google already indexed the old Webflow site, under paths like
 * /stories/<slug>, /team-content/<slug> and /portfolio/<slug>. Every one of
 * those must 301 to its new home or the ranking is lost.
 *
 * Post and project (case study) slugs come from Sanity so each old URL goes to the exact
 * matching page; anything without a match falls back to the section index.
 *
 * Runs automatically before `astro build` (see package.json).
 */
import { createClient } from "@sanity/client";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

// Minimal .env reader; real environment variables win.
const envFile = path.join(root, ".env");
const fileEnv = existsSync(envFile)
  ? Object.fromEntries(
      readFileSync(envFile, "utf8")
        .split("\n")
        .filter((l) => l.includes("=") && !l.trim().startsWith("#"))
        .map((l) => [l.slice(0, l.indexOf("=")).trim(), l.slice(l.indexOf("=") + 1).trim()])
    )
  : {};
const env = { ...fileEnv, ...process.env };

let postSlugs = [];
let projectSlugs = [];
if (env.PUBLIC_SANITY_PROJECT_ID) {
  try {
    const client = createClient({
      projectId: env.PUBLIC_SANITY_PROJECT_ID,
      dataset: env.PUBLIC_SANITY_DATASET || "production",
      apiVersion: "2026-11-01",
      useCdn: false,
      ...(env.SANITY_API_TOKEN ? { token: env.SANITY_API_TOKEN } : {}),
    });
    [postSlugs, projectSlugs] = await Promise.all([
      client.fetch(`*[_type == "post" && defined(slug.current)].slug.current`),
      client.fetch(`*[_type == "project" && defined(slug.current) && count(body) > 0].slug.current`),
    ]);
  } catch (error) {
    console.warn("[redirects] Sanity fetch failed, using section fallbacks only:", error.message);
  }
}

const lines = [];
const add = (from, to, status = 301) => lines.push(`${from} ${to} ${status}`);
const section = (title) => lines.push("", `# ${title}`);

lines.push("# Generated by scripts/generate-redirects.mjs. Do not edit by hand.");

section("Sitemap: the old Webflow sitemap URL is still submitted in Search Console");
add("/sitemap.xml", "/sitemap-index.xml");

section("Old Webflow articles: topical renames (old slug has no page; closest new article)");
const postAliases = {
  "colors-in-web-design-harnessing-the-power-of-emotions": "the-psychology-of-color-in-web-design",
  "comparing-top-website-builders": "top-10-website-builders-dee7-studio-picks",
  "create-a-landing-page-using-carrd": "design-and-develop-your-website-with-carrd-a-comprehensive-guide",
  "nick-saraevs-automations": "make-com-automation-list",
  "webflow-development-process": "webflow-development-crafting-dynamic-websites-with-ease",
  "understanding-cms-on-webflow": "the-rise-of-cms-why-content-management-systems-are-essential",
  awwwards: "top-12-websites-for-unmatched-web-design-inspiration-and-creativity",
  "dribbble-design-inspiration": "top-12-websites-for-unmatched-web-design-inspiration-and-creativity",
};
const knownPosts = new Set(postSlugs);
for (const [oldSlug, newSlug] of Object.entries(postAliases)) {
  if (knownPosts.has(newSlug) && !knownPosts.has(oldSlug)) {
    add(`/stories/${oldSlug}`, `/blog/${newSlug}`);
    add(`/team-content/${oldSlug}`, `/blog/${newSlug}`);
  }
}

section("Old Webflow articles: exact matches");
for (const slug of postSlugs) {
  add(`/stories/${slug}`, `/blog/${slug}`);
  add(`/team-content/${slug}`, `/blog/${slug}`);
}

section("Old Webflow portfolio: known renames, then exact matches");
const projectAliases = {
  weno: "weno-travel",
  "dropservicing-blueprint": "dropservicing",
  "white-invoice-app": "white-invoice",
  "05-creator-clip": "creator-clip",
  fiverr: "fiverr-dashboard",
};
const knownProjects = new Set(projectSlugs);
for (const [oldSlug, newSlug] of Object.entries(projectAliases)) {
  if (knownProjects.has(newSlug)) add(`/portfolio/${oldSlug}`, `/work/${newSlug}`);
}
for (const slug of projectSlugs) {
  if (!Object.hasOwn(projectAliases, slug)) add(`/portfolio/${slug}`, `/work/${slug}`);
}

section("Old Webflow sections: fallbacks when there is no one-to-one page");
add("/stories", "/blog");
add("/stories/*", "/blog");
add("/team-content", "/blog");
add("/team-content/*", "/blog");
add("/portfolio", "/work");
add("/portfolio/*", "/work");
add("/service", "/services");
add("/service/*", "/services");
add("/shop", "/services");
add("/shop/*", "/services");
add("/form/*", "/contact");
add("/about-us", "/");

section("Old Webflow legal pages");
add("/support/privacy-policy", "/privacy");
add("/support/cookie-policy", "/privacy");
add("/support/terms-and-conditions", "/");

const out = lines.join("\n") + "\n";
writeFileSync(path.join(root, "public/_redirects"), out);
console.log(
  `[redirects] wrote public/_redirects (${lines.filter((l) => l && !l.startsWith("#")).length} rules, ` +
    `${postSlugs.length} posts, ${projectSlugs.length} projects)`
);
